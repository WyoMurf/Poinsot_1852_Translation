import urllib.request
import json
import base64
import subprocess
import os
import time
import sys

API_KEY_PATH = "/home/murf/gemini-api-key.txt"
PDF_PATH = "/home/murf/Library/Poinsot-1852-thorienouvelled01poingoog.pdf"
OUT_FILE = "/home/murf/Poinsot_Translation.md"
LOG_FILE = "/home/murf/translation_script.log"

START_PAGE = 14 # Start translating from here (Page 10-13 were mostly done or intro)
END_PAGE = 150  # Adjust as needed, the document has about 150 pages

# We use gemini-1.5-flash to be respectful of rate limits while still being excellent at OCR/Translation
# If you prefer 1.5-pro, you can change the URL below.
MODEL_NAME = "gemini-2.5-flash" 

def log(msg):
    print(msg)
    with open(LOG_FILE, "a") as f:
        f.write(msg + "\n")

def extract_page_image(page_num):
    img_prefix = f"/tmp/poinsot_page_{page_num}"
    # Extract as a single jpeg file
    subprocess.run(["pdftoppm", "-jpeg", "-f", str(page_num), "-l", str(page_num), "-singlefile", PDF_PATH, img_prefix])
    return img_prefix + ".jpg"

def translate_image(img_path, api_key):
    with open(img_path, "rb") as f:
        img_data = base64.b64encode(f.read()).decode("utf-8")

    url = f"https://generativelanguage.googleapis.com/v1beta/models/{MODEL_NAME}:generateContent?key={api_key}"
    
    prompt = (
        "You are an expert translator and mathematician. "
        "Translate the French text in this image into English. "
        "Convert ALL mathematical equations and formulas into OpenOffice Math (StarMath) syntax "
        "(e.g., `{a} over {b}`, `int from {a} to {b} f(x) dx`, `p x + q y = %theta h`). "
        "Output ONLY the translated English text and the OpenOffice Math equations. "
        "Maintain the paragraph structure. Do not include any conversational filler."
    )

    payload = {
        "contents": [{
            "parts": [
                {"text": prompt},
                {"inline_data": {"mime_type": "image/jpeg", "data": img_data}}
            ]
        }],
        "generationConfig": {"temperature": 0.2}
    }

    req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers={"Content-Type": "application/json"})
    
    max_retries = 5
    for attempt in range(max_retries):
        try:
            with urllib.request.urlopen(req) as response:
                res_data = json.loads(response.read().decode("utf-8"))
                if "candidates" in res_data and res_data["candidates"]:
                    return res_data["candidates"][0]["content"]["parts"][0]["text"]
                else:
                    return "[No content generated by API for this page]"
        except urllib.error.HTTPError as e:
            err_msg = e.read().decode("utf-8")
            log(f"HTTP Error: {e.code} - {err_msg}")
            if e.code == 429:
                log("Rate limit hit (429). Sleeping for 60 seconds...")
                time.sleep(60)
            else:
                time.sleep(10)
        except Exception as e:
            log(f"Error: {e}")
            time.sleep(10)
    return "[Translation failed for this page after multiple attempts]"

def main():
    if not os.path.exists(API_KEY_PATH):
        log("API Key file not found!")
        sys.exit(1)
        
    api_key = open(API_KEY_PATH).read().strip()
    
    with open(OUT_FILE, "a") as f:
        f.write("\n\n--- Automated Translation Started ---\n\n")

    log(f"Starting translation from page {START_PAGE} to {END_PAGE}")

    for page in range(START_PAGE, END_PAGE + 1):
        log(f"Processing page {page}...")
        img_file = extract_page_image(page)
        
        if os.path.exists(img_file):
            translation = translate_image(img_file, api_key)
            
            with open(OUT_FILE, "a") as f:
                f.write(f"\n\n### Page {page}\n\n")
                f.write(translation)
            
            os.remove(img_file)
            
            # Respect rate limits (15 Requests Per Minute free tier = 1 request every 4 seconds)
            time.sleep(5)
        else:
            log(f"Could not extract page {page}")

    log("Translation complete.")

if __name__ == "__main__":
    main()
